// sealservers encrypts the list of featured servers with the access code, so the launcher binary
// (which is public on GitHub) does not contain the server addresses.
//
//	go run ./tools/sealservers <servers.json> <code> > servers_sealed.go
package main

import (
	"bytes"
	"encoding/base64"
	"encoding/json"
	"fmt"
	"os"

	"opcl/packcrypt"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: sealservers <servers.json> <code>")
		os.Exit(2)
	}
	b, err := os.ReadFile(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	var probe []map[string]any
	if err := json.Unmarshal(b, &probe); err != nil || len(probe) == 0 {
		fmt.Fprintln(os.Stderr, "bad servers.json:", err)
		os.Exit(1)
	}
	var out bytes.Buffer
	if err := packcrypt.Encrypt(&out, bytes.NewReader(b), os.Args[2]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("// Code generated by tools/sealservers. DO NOT EDIT.\n\npackage main\n\nvar sealedServers = %q\n",
		base64.StdEncoding.EncodeToString(out.Bytes()))
}
